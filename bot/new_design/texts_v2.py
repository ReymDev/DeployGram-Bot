def project_card(name: str, status: str, uptime: str, memory: float, cpu: float) -> str:
    """Карточка проекта в минималистичном стиле."""
    status_emoji = {"running": "🟢", "stopped": "⚫", "error": "🔴"}.get(status, "⚪")
    status_text = {"running": "Работает", "stopped": "Остановлен", "error": "Ошибка"}.get(status, "Неизвестно")
    
    # Прогресс-бар для CPU
    cpu_bar = _create_progress_bar(cpu, 100)
    
    return f"""<b>{status_emoji} {name}</b>

Статус: {status_text}
Время работы: {uptime}

💾 RAM: <b>{memory:.0f} MB</b>
⚡ CPU: <b>{cpu:.1f}%</b>
{cpu_bar}"""


def _create_progress_bar(value: float, max_value: float, length: int = 10) -> str:
    """Создаёт текстовый прогресс-бар."""
    filled = int((value / max_value) * length)
    empty = length - filled
    
    if value >= 80:
        bar_char = "🟥"
    elif value >= 50:
        bar_char = "🟨"
    else:
        bar_char = "🟩"
    
    return bar_char * filled + "⬜" * empty


